def outside_us(location: str | None, country_hint: str | None = None) -> bool:
    """True only when the location (or the source's country hint) names somewhere abroad and nothing in the US."""
    text = " ; ".join(x for x in (location, country_hint) if x)
    if not text.strip():
        return False
    if _US.search(text) or _US_ABBR.search(text):
        return False
    return bool(_ABROAD.search(text))
