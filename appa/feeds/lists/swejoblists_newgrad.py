"""swejoblists.com 2027 new-grad list: a GitHub mirror (TheoXiong7/2027-New-Grad-SWE-Jobs) of the
swejoblists.com aggregator, regenerated by the site several times a day. The README is one Markdown pipe
table of at most 1,000 rows (Company | Role | Location | H-1B | Posted); every link goes to the role's
swejoblists.com page, not the employer's ATS, and the H-1B column is the site's model estimate. It mixes
in consultancy, staffing and non-software roles, so it is low priority: a discovery source.

fetch() reads the mirror README once per run (descriptions empty). describe() fetches one role page
(/jobs/<slug>, allowed by robots.txt and by terms s.3: "browse, follow job links ... automated access must
respect published access rules and rate limits") only for listings that pass appa's filters, and returns
the posting text plus the employer's real apply link. The site's paginated lists are not crawled.
"""

from __future__ import annotations

import json
import re
from datetime import UTC, date, datetime, timedelta
from urllib.parse import quote, urlsplit

from bs4 import BeautifulSoup

from appa.feeds import FeedOptions, ListFeed, Listing, register_list
from appa.sources.http import get_text
from appa.sources.text import html_to_text, mark_hidden

URL = "https://raw.githubusercontent.com/TheoXiong7/2027-New-Grad-SWE-Jobs/main/README.md"
SITE = "https://swejoblists.com"
MAX_DESC = 100_000
HEADER = ["company", "role", "location", "h-1b", "posted"]
H1B = {"yes", "likely", "unlikely", "no"}
MONTHS = {
    m: i for i, m in enumerate(("jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"), 1)
}

_PIPE = re.compile(r"(?<!\\)\|")
_LINK = re.compile(r"^\[(.*)\]\((https?://[^)\s]+)\)$", re.S)
_JOB = re.compile(r"^/jobs/([a-z0-9][a-z0-9-]{0,180}-(\d{1,12}))/?$")
_UPDATED = re.compile(r"Last update:\s*(\d{4}-\d{2}-\d{2})")
_AGE = re.compile(r"^(\d{1,4})d$")
_DAY = re.compile(r"^([A-Za-z]{3})\s+(\d{1,2})$")
_SLUG = re.compile(r"^[a-z0-9][a-z0-9-]{0,180}-\d{1,12}$")
_REMOTE = re.compile(r"\bremote\b", re.I)
_NOT_REMOTE = re.compile(r"\b(not|non)[\s-]*remote\b", re.I)


def _cells(line: str) -> list[str]:
    """The cells of one Markdown table row, splitting only on unescaped pipes."""
    return [c.strip().replace("\\|", "|") for c in _PIPE.split(line.strip().strip("|"))]


def _link(cell: str) -> tuple[str, str]:
    """(text, url) of a '[text](url)' cell, or (plain text, '') when it isn't a link."""
    m = _LINK.match(cell)
    return (m.group(1).strip(), m.group(2)) if m else (cell.strip(), "")


def _job(url: str) -> tuple[str, str] | None:
    """(slug, numeric id) of a swejoblists.com role link, or None for any other link."""
    parts = urlsplit(url)
    if (parts.hostname or "").lower() not in ("swejoblists.com", "www.swejoblists.com"):
        return None
    m = _JOB.match(parts.path)
    return (m.group(1), m.group(2)) if m else None


def _posted(cell: str, today: date) -> date | None:
    """The posting date from an age ('3d') or a month-day ('Oct 16', the latest such date not after today)."""
    if m := _AGE.match(cell):
        return today - timedelta(days=int(m.group(1)))
    if (m := _DAY.match(cell)) and m.group(1).lower() in MONTHS:
        for year in (today.year, today.year - 1):
            try:
                d = date(year, MONTHS[m.group(1).lower()], int(m.group(2)))
            except ValueError:
                continue
            if d <= today:
                return d
    return None


def _remote(loc: str) -> str | None:
    """'hybrid' or 'yes' when the location says so; None when it is silent, negated or ambiguous."""
    if "hybrid" in loc.lower():
        return "hybrid"
    if _REMOTE.search(loc) and not _NOT_REMOTE.search(loc):
        return "yes"
    return None


def _listing(cells: list[str], today: date) -> Listing | None:
    """A Listing from one table row, or None when the row is malformed or doesn't link a role page."""
    if len(cells) != 5:
        return None
    company, _ = _link(cells[0])
    title, url = _link(cells[1])
    job = _job(url)
    if not job:
        return None
    slug, jid = job
    h1b = cells[3].strip()
    hints = {"level": "new_grad"}
    if h1b.lower() in H1B:
        hints["sponsorship"] = f"H-1B: {h1b} (swejoblists estimate)"
    if remote := _remote(cells[2]):
        hints["remote"] = remote
    try:
        return Listing(
            company=company,
            title=title,
            url=f"{SITE}/jobs/{slug}",
            location=cells[2][:500],
            posted_at=_posted(cells[4], today),
            ats_job_id=jid,
            source_ref=slug,
            hints=hints,
        )
    except ValueError:
        return None


def parse(text: str, today: date | None = None) -> list[Listing]:
    """Every role in the README table, in file order (newest first), deduped on the swejoblists role ID only."""
    if today is None:
        m = _UPDATED.search(text)
        today = date.fromisoformat(m.group(1)) if m else datetime.now(UTC).date()
    out, seen, in_table = [], set(), False
    for line in text.splitlines():
        if not line.startswith("|"):
            in_table = False
            continue
        cells = _cells(line)
        if [c.lower() for c in cells] == HEADER:
            in_table = True
            continue
        if not in_table or set(line) <= set("|-: "):
            continue
        x = _listing(cells, today)
        if x is None:
            continue
        if x.ats_job_id not in seen:
            seen.add(x.ats_job_id)
            out.append(x)
    return out


def fetch(opts: FeedOptions) -> list[Listing]:
    """The README's roles (up to 1,000, newest first), optionally only those posted since opts.since."""
    text, _ = get_text(URL)
    out = parse(text)
    if opts.since:
        out = [x for x in out if x.posted_at is None or x.posted_at >= opts.since]
    return out[: opts.max_results]


def _ld_description(soup: BeautifulSoup) -> str:
    """The HTML description from the page's JobPosting ld+json block, or '' when there is none."""
    for tag in soup.find_all("script", type="application/ld+json"):
        try:
            data = json.loads(tag.string or "")
        except ValueError:
            continue
        if isinstance(data, dict) and data.get("@type") == "JobPosting" and isinstance(data.get("description"), str):
            return data["description"]
    return ""


def _apply_url(soup: BeautifulSoup) -> str:
    """The employer's apply link (the page's 'Apply' button) when it is an off-site http(s) URL, else ''."""
    a = soup.find("a", attrs={"data-apply": True})
    href = (a.get("href") or "").strip() if a else ""
    parts = urlsplit(href)
    host = (parts.hostname or "").lower()
    if (
        parts.scheme not in ("http", "https")
        or not host
        or host == "swejoblists.com"
        or host.endswith(".swejoblists.com")
    ):
        return ""
    return href[:2000]


def describe(listing: Listing) -> str:
    """The role page's posting text (hidden text flagged) plus an 'Apply: <employer url>' line; one request."""
    slug = listing.source_ref or ""
    if not _SLUG.match(slug):
        raise ValueError(f"not a swejoblists role slug: {slug[:100]!r}")
    page, _ = get_text(f"{SITE}/jobs/{quote(slug, safe='')}")
    soup = BeautifulSoup(page, "html.parser")
    raw = _ld_description(soup)
    if not raw:
        div = soup.find("div", attrs={"data-description": True})
        raw = div.decode_contents() if div else ""
    text = mark_hidden(*html_to_text(raw)) if raw else ""
    text = text[:MAX_DESC]
    if apply := _apply_url(soup):
        text = f"{text}\n\nApply: {apply}".strip()
    return text


FEED = register_list(
    ListFeed(
        name="swejoblists_newgrad",
        description="swejoblists.com 2027 new-grad list (GitHub mirror): up to 1,000 roles linking swejoblists "
        "pages (describe() adds the posting text and employer apply link); noisy (staffing, non-SWE), "
        "H-1B estimates; discovery only",
        fetch=fetch,
        describe=describe,
        terms="swejoblists.com/terms s.3: browsing, following job links and using the public exports are allowed; "
        "automated access must respect published access rules and rate limits (no overloading, bypassing "
        "access controls or scraping restricted account data). robots.txt allows /jobs/ and disallows "
        "/readme/, /api/ and /download/jobs.csv. appa reads the GitHub mirror README once per run and fetches "
        "single role pages only for listings that pass the filters.",
    )
)
